async function upsertCustomer(row: CustomerSeedRow) {
  const existing = row.tinNumber
    ? await prisma.customer.findFirst({ where: { tinNumber: row.tinNumber } })
    : await prisma.customer.findFirst({ where: { name: { equals: row.name, mode: "insensitive" } } });

  if (existing) {
    await prisma.customer.update({
      where: { id: existing.id },
      data: {
        name: row.name,
        tinNumber: row.tinNumber,
        phone: row.phone,
        isActive: true,
      },
    });
    return "updated" as const;
  }

  await prisma.customer.create({
    data: {
      name: row.name,
      tinNumber: row.tinNumber,
      phone: row.phone,
      isActive: true,
    },
  });
  return "created" as const;
}

async function main() {
  let created = 0;
  let updated = 0;

  for (const row of CUSTOMER_SEED_ROWS) {
    const result = await upsertCustomer(row);
    if (result === "created") created += 1;
    if (result === "updated") updated += 1;
  }

  console.log(`Customer seed completed from embedded ${CUSTOMER_SEED_SOURCE.sourceSheet} data.`);
  console.log(`Rows read: ${CUSTOMER_SEED_ROWS.length}`);
  console.log(`Rows with phone: ${CUSTOMER_SEED_SOURCE.rowsWithPhone}`);
  console.log(`Created: ${created}`);
  console.log(`Updated: ${updated}`);
}

